"""Read existing item artwork backgrounds for their Flutter container colors."""
from pathlib import Path
import re
from statistics import median

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def background(path):
    with Image.open(path) as source:
        image = source.convert('RGBA')
        width, height = image.size
        colors = []
        # Sample clear background near the four edges, away from central artwork.
        for x, y in ((.5, .08), (.08, .5), (.92, .5), (.5, .92)):
            center_x, center_y = round(x * width), round(y * height)
            for dx in range(-3, 4):
                for dy in range(-3, 4):
                    r, g, b, a = image.getpixel((center_x + dx, center_y + dy))
                    if a >= 240 and r >= 160 and g - r >= 5 and g - b >= 8:
                        colors.append((r, g, b))
        if not colors:
            raise ValueError(f'No green background found in {path}')
        return ''.join(f'{round(median(channel)):02X}' for channel in zip(*colors))


def generate():
    model = (ROOT / 'lib/models/item_icon.dart').read_text(encoding='utf-8')
    names = re.findall(r"ItemIcon\(\s*'([^']+)'", model)
    assets = ['assets/icons/home/default_avatar.png'] + [
        f'assets/icons/inventory/{name}.png' for name in names
    ]
    entries = '\n'.join(
        f"    '{asset}': 0xFF{background(ROOT / asset)}," for asset in assets
    )
    (ROOT / 'lib/models/item_artwork_palette.dart').write_text(
        '// Generated by scripts/generate_item_artwork_palette.py.\n'
        '// Colors are sampled from the existing artwork; source images are unchanged.\n'
        'abstract final class ItemArtworkPalette {\n'
        '  static int backgroundArgb(String asset) => _colors[asset] ?? 0xFFE5F4DB;\n\n'
        '  static const _colors = <String, int>{\n'
        f'{entries}\n'
        '  };\n'
        '}\n',
        encoding='utf-8',
    )
    print(f'Generated background colors for {len(assets)} item artwork assets.')


if __name__ == '__main__':
    generate()
