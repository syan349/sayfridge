"""Print reviewable PostgreSQL seed SQL from the catalog. Never connects to a database."""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.core.category_catalog import CATEGORIES


SCHEMA_PATTERN = re.compile(r"^[a-z_][a-z0-9_]*$")


def render_seed_sql(schema_name: str = "public"):
    if not SCHEMA_PATTERN.fullmatch(schema_name):
        raise ValueError("schema_name must be a lowercase PostgreSQL identifier")
    schema = "public" if schema_name == "public" else f'"{schema_name}"'
    category_table = f"{schema}.item_category"

    def quote(value):
        return "'" + value.replace("'", "''") + "'"
    rows = ",\n".join(
        f"    ({quote(c['name'])}, {quote(c['normalized_name'])}, {c['sort_order']})"
        for c in CATEGORIES
    )
    return f"""-- Generated by scripts/render_category_seed.py; review before execution.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
LOCK TABLE {category_table} IN SHARE ROW EXCLUSIVE MODE;
CREATE TEMP TABLE category_seed (name TEXT, normalized_name TEXT, sort_order INTEGER) ON COMMIT DROP;
INSERT INTO category_seed VALUES
""" + rows + f""";
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM {category_table} c JOIN category_seed s USING (normalized_name)
        WHERE c.status <> 'ACTIVE'
    ) THEN
        RAISE EXCEPTION 'A seed category is archived; review it explicitly before continuing';
    END IF;
    IF EXISTS (
        SELECT 1 FROM {category_table} c JOIN category_seed s
          ON lower(btrim(normalize(c.name, NFKC))) = s.normalized_name
        WHERE c.normalized_name <> s.normalized_name
    ) THEN
        RAISE EXCEPTION 'A legacy category name has a different normalized key; review before continuing';
    END IF;
END $$;
INSERT INTO {category_table} (id, name, normalized_name, status, sort_order)
SELECT gen_random_uuid(), name, normalized_name, 'ACTIVE', sort_order FROM category_seed
ON CONFLICT (normalized_name) DO NOTHING;
COMMIT;
"""


if __name__ == "__main__":
    print(render_seed_sql(), end="")
